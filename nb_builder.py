"            pos = sum(1 for k in ['gain','rally','surge','oversubscribed','bullish','profit'] if k in tl)\n",
"            neg = sum(1 for k in ['loss','crash','below','bearish','fraud','fall','weak'] if k in tl)\n",
"            kw  = (pos - neg) / max(pos + neg, 1)\n",
"            scores.append(vs*0.4 + tb*0.3 + kw*0.3)\n",
"        avg = sum(scores) / len(scores)\n",
"        return round(max(0, min(100, 50 + avg * 50)), 1)\n",
"    except Exception:\n",
"        return 50.0\n",
"\n",
"# ── Agent 4: Risk Agent ─────────────────────────────────────────────────────\n",
