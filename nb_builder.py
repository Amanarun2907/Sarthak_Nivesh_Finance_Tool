"# Cell 4: Agent Signal Generation — Exact Framework Logic\n",
"# ========================================================\n",
"\n",
"# ── Agent 1: Price Movement Agent ──────────────────────────────────────────\n",
"def agent_price(issue, listing, sub):\n",
"    score = 50.0\n",
"    lg = (listing - issue) / issue * 100\n",
"    if lg > 50:    score += 12\n",
"    elif lg > 25:  score += 8\n",
"    elif lg > 10:  score += 4\n",
"    elif lg < -10: score -= 10\n",
"    elif lg < 0:   score -= 5\n",
"    if sub > 50:   score += 8\n",
"    elif sub > 20: score += 5\n",
"    elif sub > 5:  score += 2\n",
"    elif sub < 2:  score -= 6\n",
"    return round(max(0, min(100, score)), 1)\n",
"\n",
"# ── Agent 2: Macroeconomic Agent ───────────────────────────────────────────\n",
"def agent_macro(date_str):\n",
"    try:\n",
"        ld = datetime.strptime(date_str, '%Y-%m-%d')\n",
"        h  = yf.Ticker('^NSEI').history(\n",
"            start=(ld - timedelta(7)).strftime('%Y-%m-%d'),\n",
"            end=(ld + timedelta(2)).strftime('%Y-%m-%d'))\n",
"        if h.empty or len(h) < 2:\n",
"            return 50.0\n",
"        chg = (h['Close'].iloc[-1] - h['Close'].iloc[0]) / h['Close'].iloc[0] * 100\n",
"        score = 50.0 + (15 if chg>3 else 8 if chg>1 else 3 if chg>0\n",
"                        else -15 if chg<-3 else -8 if chg<-1 else -3)\n",
"        return round(max(0, min(100, score)), 1)\n",
"    except Exception:\n",
"        return 50.0\n",
"\n",
"# ── Agent 3: Sentiment Agent ────────────────────────────────────────────────\n",
"def agent_sentiment(ipo_name):\n",
