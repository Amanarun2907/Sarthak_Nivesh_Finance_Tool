"    elif lg < -15: score -= 20\n",
"    elif lg < -5:  score -= 12\n",
"    else:          score -= 6\n",
"    if sub > 100:  score += 10\n",
"    elif sub > 50: score += 6\n",
"    elif sub > 10: score += 3\n",
"    elif sub < 2:  score -= 8\n",
"    return round(max(0, min(100, score)), 1)\n",
