"    if lg > 50:    score += 12\n",
"    elif lg > 25:  score += 8\n",
"    elif lg > 10:  score += 5\n",
"    elif lg < -10: score -= 12\n",
"    elif lg < 0:   score -= 6\n",
"    if qib > 100:  score += 12\n",
"    elif qib > 50: score += 8\n",
"    elif qib > 20: score += 4\n",
"    elif qib < 5:  score -= 8\n",
"    elif qib < 2:  score -= 12\n",
"    if sub > 50:   score += 5\n",
