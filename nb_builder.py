"        q   = ipo_name.replace(' ', '+') + '+IPO+India'\n",
"        url = 'https://news.google.com/rss/search?q=' + q + '&hl=en-IN&gl=IN&ceid=IN:en'\n",
"        r   = requests.get(url, timeout=8, headers={'User-Agent':'Mozilla/5.0'})\n",
"        if r.status_code != 200:\n",
"            return 50.0\n",
"        from bs4 import BeautifulSoup\n",
"        soup   = BeautifulSoup(r.content, 'xml')\n",
"        titles = [it.title.text for it in soup.find_all('item')[:8] if it.title]\n",
"        if not titles:\n",
"            return 50.0\n",
"        scores = []\n",
"        for t in titles:\n",
"            vs = VADER.polarity_scores(t)['compound']\n",
"            try:    tb = TextBlob(t).sentiment.polarity\n",
